export enum PlaceCategory {
  Restaurant = "餐廳",
  Attraction = "景點",
  Shopping = "購物",
  Lodging = "住宿",
}

type BasePlace = {
  id: string;
  name: string;
  nameJa: string;
  categoryEn: string;
  position: [number, number] | null;
  address: string;
  hours: string;
  stay: string;
  note: string;
  tags: string[];
  maps: string;
  official?: string;
  verified?: boolean;
};

export type TabelogInfo = {
  url: string;
  rating?: number;
  verifiedAt?: string;
};

type RestaurantPlace = BasePlace & {
  category: PlaceCategory.Restaurant;
  tabelog?: TabelogInfo;
};

type NonRestaurantPlace = BasePlace & {
  category: PlaceCategory.Attraction | PlaceCategory.Shopping | PlaceCategory.Lodging;
  tabelog?: never;
};

export type Place = RestaurantPlace | NonRestaurantPlace;

type DraftPlaceInput = Pick<
  BasePlace,
  "id" | "name" | "note" | "tags" | "maps" | "position" | "hours"
> & {
  nameJa?: string;
  address?: string;
  official?: string;
};

function draftRestaurant(
  input: DraftPlaceInput & Pick<RestaurantPlace, "tabelog">,
): RestaurantPlace {
  return {
    ...input,
    nameJa: input.nameJa ?? input.name,
    category: PlaceCategory.Restaurant,
    categoryEn: "RESTAURANT",
    address: input.address ?? "請參考 Google Maps",
    stay: "建議停留 45–90 分鐘",
    verified: true,
  };
}

function draftNonRestaurant(
  category: PlaceCategory.Attraction | PlaceCategory.Shopping | PlaceCategory.Lodging,
  input: DraftPlaceInput,
): NonRestaurantPlace {
  return {
    ...input,
    nameJa: input.nameJa ?? input.name,
    category,
    categoryEn:
      category === PlaceCategory.Attraction
        ? "ATTRACTION"
        : category === PlaceCategory.Shopping
          ? "SHOPPING"
          : "LODGING",
    address: input.address ?? "請參考 Google Maps",
    stay:
      category === PlaceCategory.Attraction
        ? "建議停留 60–120 分鐘"
        : category === PlaceCategory.Shopping
          ? "建議停留 45–90 分鐘"
          : "住宿期間 4 晚",
    verified: true,
  };
}

